"""
api_client.py
=============
Open-Meteo API integration client for live weather forecasting and ML comparison.

Open-Meteo provides free, open-source weather forecasts generated by global
Numerical Weather Prediction (NWP) models (such as ECMWF, GFS, and ICON).

This module handles:
1. Fetching current observations, today's daily aggregate, and tomorrow's forecast.
2. Fetching recent past observations (yesterday) to build valid lag features for the ML model.
3. Graceful error handling (timeouts, connection drops, API errors).
4. Feature adaptation for the ML vs NWP side-by-side comparison mode.
"""

from typing import Dict, Any, Optional, Tuple
import datetime
import requests
import pandas as pd
from data_loader import CITIES_METADATA, MODEL_FEATURE_NAMES, get_wmo_info

OPEN_METEO_BASE_URL = "https://api.open-meteo.com/v1/forecast"


def fetch_live_city_weather(city_name: str, timeout: int = 8) -> Dict[str, Any]:
    """
    Fetch live weather conditions and multi-day forecast for the specified Indian city.
    
    Includes:
    - Real-time current weather (temperature, humidity, wind, weather code).
    - Yesterday's observed values (used for previous_rain & previous_max_temp lag features).
    - Today's observed/forecasted max, min, rain, wind.
    - Tomorrow's NWP forecast (for side-by-side comparison with ML model).
    - 7-day daily forecast for interactive charts.
    """
    city_info = CITIES_METADATA.get(city_name)
    if not city_info:
        return {
            "success": False,
            "error": f"City '{city_name}' is not recognized in supported cities."
        }

    params = {
        "latitude": city_info["lat"],
        "longitude": city_info["lon"],
        "current": (
            "temperature_2m,relative_humidity_2m,apparent_temperature,"
            "precipitation,rain,weather_code,wind_speed_10m"
        ),
        "daily": (
            "temperature_2m_max,temperature_2m_min,precipitation_sum,"
            "rain_sum,precipitation_probability_max,weather_code,wind_speed_10m_max"
        ),
        "timezone": "Asia/Kolkata",
        "past_days": 2,  # Fetch past 2 days so yesterday's lag features are guaranteed
        "forecast_days": 7
    }

    try:
        response = requests.get(OPEN_METEO_BASE_URL, params=params, timeout=timeout)
        if response.status_code != 200:
            return {
                "success": False,
                "error": f"Open-Meteo API returned HTTP status {response.status_code}."
            }

        data = response.json()
        current = data.get("current", {})
        daily = data.get("daily", {})

        # Parse daily lists
        dates = daily.get("time", [])
        if not dates:
            return {
                "success": False,
                "error": "Incomplete data returned by Open-Meteo."
            }

        today_str = datetime.date.today().strftime("%Y-%m-%d")
        
        # Locate today's index in the daily response
        try:
            today_idx = dates.index(today_str)
        except ValueError:
            # Fallback to index 2 (since past_days=2, index 0 is 2 days ago, index 1 is yesterday, index 2 is today)
            today_idx = min(2, len(dates) - 1)

        # Yesterday
        yesterday_idx = max(0, today_idx - 1)
        yesterday_data = {
            "date": dates[yesterday_idx],
            "temp_max": daily["temperature_2m_max"][yesterday_idx],
            "temp_min": daily["temperature_2m_min"][yesterday_idx],
            "rain_sum": daily.get("rain_sum", daily.get("precipitation_sum", [0]))[yesterday_idx],
            "wind_speed_max": daily["wind_speed_10m_max"][yesterday_idx],
        }

        # Today
        today_data = {
            "date": dates[today_idx],
            "temp_max": daily["temperature_2m_max"][today_idx],
            "temp_min": daily["temperature_2m_min"][today_idx],
            "rain_sum": daily.get("rain_sum", daily.get("precipitation_sum", [0]))[today_idx],
            "wind_speed_max": daily["wind_speed_10m_max"][today_idx],
            "rain_prob_max": daily.get("precipitation_probability_max", [None])[today_idx],
            "weather_code": daily.get("weather_code", [0])[today_idx],
        }

        # Tomorrow
        tomorrow_idx = min(today_idx + 1, len(dates) - 1)
        tomorrow_data = {
            "date": dates[tomorrow_idx],
            "temp_max": daily["temperature_2m_max"][tomorrow_idx],
            "temp_min": daily["temperature_2m_min"][tomorrow_idx],
            "rain_sum": daily.get("rain_sum", daily.get("precipitation_sum", [0]))[tomorrow_idx],
            "rain_prob_max": daily.get("precipitation_probability_max", [None])[tomorrow_idx],
            "weather_code": daily.get("weather_code", [0])[tomorrow_idx],
            "wind_speed_max": daily["wind_speed_10m_max"][tomorrow_idx],
        }

        # Weather descriptions
        current_wmo_text, current_wmo_icon = get_wmo_info(current.get("weather_code"))
        tomorrow_wmo_text, tomorrow_wmo_icon = get_wmo_info(tomorrow_data.get("weather_code"))

        # Build full 7-day daily forecast table
        forecast_table = []
        rain_prob_list = daily.get("precipitation_probability_max", [])
        rain_sum_list = daily.get("rain_sum", daily.get("precipitation_sum", []))
        weather_codes = daily.get("weather_code", [])

        for i in range(today_idx, len(dates)):
            wmo_code = weather_codes[i] if i < len(weather_codes) else 0
            wmo_txt, wmo_ico = get_wmo_info(wmo_code)
            r_sum = rain_sum_list[i] if i < len(rain_sum_list) and rain_sum_list[i] is not None else 0.0
            r_prob = rain_prob_list[i] if i < len(rain_prob_list) and rain_prob_list[i] is not None else 0

            forecast_table.append({
                "date": dates[i],
                "day_name": datetime.datetime.strptime(dates[i], "%Y-%m-%d").strftime("%a"),
                "temp_max": daily["temperature_2m_max"][i],
                "temp_min": daily["temperature_2m_min"][i],
                "rain_sum": r_sum,
                "rain_prob": r_prob,
                "rain_prob_max": r_prob,
                "condition": f"{wmo_ico} {wmo_txt}",
                "condition_text": wmo_txt,
                "condition_icon": wmo_ico,
            })

        return {
            "success": True,
            "city": city_name,
            "current": {
                "time": current.get("time"),
                "temperature": current.get("temperature_2m"),
                "apparent_temperature": current.get("apparent_temperature"),
                "humidity": current.get("relative_humidity_2m"),
                "wind_speed": current.get("wind_speed_10m"),
                "precipitation": current.get("precipitation", 0.0),
                "weather_code": current.get("weather_code"),
                "condition_text": current_wmo_text,
                "condition_icon": current_wmo_icon,
            },
            "today": today_data,
            "tomorrow": {
                **tomorrow_data,
                "condition_text": tomorrow_wmo_text,
                "condition_icon": tomorrow_wmo_icon
            },
            "yesterday": yesterday_data,
            "forecast_table": pd.DataFrame(forecast_table),
            "source": "Open-Meteo Global Numerical Weather Prediction (NWP) API"
        }

    except requests.exceptions.Timeout:
        return {
            "success": False,
            "error": "Connection to Open-Meteo timed out. Please check your internet connection."
        }
    except requests.exceptions.ConnectionError:
        return {
            "success": False,
            "error": "Failed to connect to Open-Meteo. Please verify network access."
        }
    except Exception as e:
        return {
            "success": False,
            "error": f"An unexpected error occurred while fetching live weather: {str(e)}"
        }


def convert_live_weather_to_ml_features(live_data: Dict[str, Any]) -> pd.DataFrame:
    """
    Construct valid 8-feature ML input vector from live Open-Meteo observations.
    
    Uses:
    - Today's observed/forecasted max temperature
    - Today's observed/forecasted min temperature
    - Today's observed rainfall
    - Today's maximum wind speed
    - Yesterday's observed rainfall (previous_rain)
    - Yesterday's observed max temperature (previous_max_temp)
    - Current month
    - Current day of the year
    """
    if not live_data.get("success"):
        raise ValueError("Cannot convert failed live weather data to features.")

    today = live_data["today"]
    yesterday = live_data["yesterday"]
    now = datetime.datetime.now()

    feature_dict = {
        "temperature_2m_max": float(today["temp_max"]),
        "temperature_2m_min": float(today["temp_min"]),
        "rain_sum": float(today["rain_sum"]),
        "wind_speed_10m_max": float(today["wind_speed_max"]),
        "previous_rain": float(yesterday["rain_sum"]),
        "previous_max_temp": float(yesterday["temp_max"]),
        "month": int(now.month),
        "day_of_year": int(now.timetuple().tm_yday)
    }

    return pd.DataFrame([[feature_dict[f] for f in MODEL_FEATURE_NAMES]], columns=MODEL_FEATURE_NAMES)
